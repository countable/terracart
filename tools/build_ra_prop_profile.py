"""Build the static opt-in asset, icon, and seating registry for approved RA props."""
from pathlib import Path
from PIL import Image
import json
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/ArtTrials/RogueProps'
assets={};bounds={};icons={}
for file in ['flora-mapping.json','containers/mapping.json']:
 data=json.loads((OUT/file).read_text());bounds.update(data['bounds'])
 for key,row in data['assets'].items():
  assets[key]={k:row[k] for k in ['kind','path','frameWidth','frameHeight'] if k in row}
  if row['kind']=='spritesheet':icons[key]=dict(url=row['path'],cols=row['width']//row['frameWidth'],srcW=row['width'],srcH=row['height'])
 if data.get('lowpolyMaterials'):assets['prop_materials']={'kind':'image','path':data['lowpolyMaterials']}
for row in json.loads((OUT/'fixtures/manifest.json').read_text())['assets']:
 assets[row['key']]=row['asset'];bounds.update(row['bounds'])
profile={'assets':assets,'bounds':bounds,'icons':icons}
(ROOT/'src/rogue_prop_profile.js').write_text('// Generated by tools/build_ra_prop_profile.py. No runtime pixel reads.\nconst ROGUE_PROP_PROFILE = '+json.dumps(profile,separators=(',',':'))+';\n')
print(len(assets),'RA texture overrides;',len(bounds),'frame bounds')
