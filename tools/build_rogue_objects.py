#!/usr/bin/env python3
"""Export the reference-selected RA objects with exact crop/assembly provenance."""
from pathlib import Path
import hashlib,json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/ArtTrials/RogueObjects';OUT.mkdir(parents=True,exist_ok=True)
rows=[]
for study,ids in [('jungle-study',['tree-wide-a','tree-wide-b','tree-root-a','tree-root-b','tree-rounded-2','tree-rounded-3','tree-dead','stone','rock-mid','lamp']),('village-study',['house-small','house-sw','house-large','ladder-down'])]:
 for row in json.loads((ROOT/'tools'/study/'assets.json').read_text()):
  if row['id'] not in ids:continue
  x,y,w,h=row['rect'];crop=Image.open(ROOT/row['source']).convert('RGBA').crop((x,y,x+w,y+h))
  for a,b,c,d in row.get('clear',[]):crop.paste((0,0,0,0),(a,b,a+c,b+d))
  for p in row.get('overlays',[]):
   a,b,c,d=p['rect'];crop.alpha_composite(Image.open(ROOT/p['source']).convert('RGBA').crop((a,b,a+c,b+d)),tuple(p['at']))
  bounds=crop.getbbox();assert bounds
  crop.save(OUT/(row['id']+'.png'))
  rows.append(dict(row,sourceSHA256=hashlib.sha256((ROOT/row['source']).read_bytes()).hexdigest(),bounds=dict(fw=w,fh=h,minX=bounds[0],minY=bounds[1],maxX=bounds[2],maxY=bounds[3])))
# The unlit condition uses the same native stone lamp base, without flame rows.
row=next(r for r in rows if r['id']=='lamp');crop=Image.open(OUT/'lamp.png');crop.paste((0,0,0,0),(0,0,16,12));crop.save(OUT/'lamp-unlit.png')
b=crop.getbbox()
rows.append(dict(row,id='lamp-unlit',bounds=dict(fw=16,fh=32,minX=b[0],minY=b[1],maxX=b[2],maxY=b[3]),clear=[[0,0,16,12]],note='Same source stone lamp with flame removed for unlit state.'))
(OUT/'manifest.json').write_text(json.dumps(rows,indent=2)+'\n')
(ROOT/'src/rogue_object_bounds.js').write_text('// Generated by tools/build_rogue_objects.py; no runtime pixel reads.\nconst ROGUE_OBJECT_BOUNDS = '+json.dumps({r['id'].replace('-','_'):r['bounds'] for r in rows},separators=(',',':'))+';\n')
# The weather exporter upserts its non-object provenance after this manifest's
# full rewrite, so either entry point keeps the rain source reproducible.
from build_ra_weather import build as build_weather
build_weather()
print('Exported',len(rows),'RA reference objects')
