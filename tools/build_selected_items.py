#!/usr/bin/env python3
"""Pack approved item choices, including relics, without resampling source pixels."""
import argparse
import io
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/Icons/SelectedItems'
CELL = 16
COLS = 8
CHOICES = {
    'amethyst': [599], 'acorn': [700], 'regeneration_amulet': [739],
    'vigor_amulet': [740], 'antidote': [611], 'apple': [492],
    'banana': [486], 'berry': [540], 'cherry': [487], 'diamond': [594],
    'egg': [387], 'elixir': [614], 'emerald': [371],
    'explosive_flask': [758, 276], 'pet_fang_charm': [741],
    'goldenberry': [698], 'poison_flask': [609, 284], 'blight_potion': [274],
    'fire_resistance_potion': [755], 'giant_potion': [327], 'grip_potion': [601],
    'hardworking_potion': [323], 'healing_potion': [605], 'immortal_potion': [222],
    'protection_potion': [281], 'reach_potion': [287], 'resurrection_potion': [603],
    'revival_potion': [602], 'shielding_potion': [228], 'speed_potion': [747],
    'stoneskin_potion': [759], 'taming_potion': [603], 'time_potion': [282],
    'pet_rest_charm': [742], 'rubble': [400], 'salmon': [495], 'sapphire': [497],
    'sugar_potion': [541], 'tome_blight': [709], 'tome_frost_aura': [708],
    'tome_healing': [617], 'tome_thunder': [714], 'torch': [279],
    'tome_fire_wall': [711], 'wood': [341],
    'relic:dagger:1': [631], 'relic:dagger:2': [657], 'relic:dagger:4': [668],
    'relic:dagger:6': [680], 'relic:dagger:7': [686], 'relic:lance:1': [640],
}


def outputs():
    registry = {e['id']: e for e in json.loads((ROOT / 'tools/art-alternative-ids.json').read_text())['entries']}
    frames, selections, crops, frame_by_alt = [], [], [], {}
    for target, numbers in CHOICES.items():
        for choice, number in enumerate(numbers):
            alt = f'ALT-{number:04}'
            if alt not in frame_by_alt:
                source = registry[alt]
                x, y, w, h = source['crop']
                if (w, h) != (CELL, CELL):
                    raise ValueError(f'{alt} is not native 16x16: {source["crop"]}')
                with Image.open(ROOT / source['source']) as image:
                    if x < 0 or y < 0 or x+w > image.width or y+h > image.height:
                        raise ValueError(f'{alt} crop exceeds source')
                    crop = image.convert('RGBA').crop((x, y, x+w, y+h))
                if crop.getchannel('A').getbbox() is None:
                    raise ValueError(f'{alt} is empty')
                frame_by_alt[alt] = len(crops)
                crops.append(crop)
                frames.append({'frame': frame_by_alt[alt], **source})
            selections.append({'target': target, 'alternativeId': alt,
                               'frame': frame_by_alt[alt], 'default': choice == 0})
    width, height = COLS * CELL, ((len(crops) + COLS - 1) // COLS) * CELL
    sheet = Image.new('RGBA', (width, height))
    for frame, crop in enumerate(crops):
        sheet.paste(crop, ((frame % COLS) * CELL, (frame // COLS) * CELL))
    png = io.BytesIO()
    sheet.save(png, format='PNG')
    runtime = {'sheet': 'selected_items', 'url': 'assets/Icons/SelectedItems/items.png',
               'cols': COLS, 'width': width, 'height': height,
               'icons': {}, 'relics': {}, 'alternatives': {}}
    for selection in selections:
        target = selection['target']
        art = {'sheet': 'selected_items', 'frame': selection['frame']}
        runtime['alternatives'].setdefault(target, []).append({**art, 'alternativeId': selection['alternativeId']})
        if not selection['default']:
            continue
        if target.startswith('relic:'):
            _, slot, tier = target.split(':')
            runtime['relics'].setdefault(slot, {})[tier] = art
        else:
            runtime['icons'][target] = art
    manifest = {'schemaVersion': 1, 'sheet': runtime['url'], 'frameWidth': CELL,
                'frameHeight': CELL, 'cols': COLS, 'width': width, 'height': height,
                'note': 'First listed selection is the default; additional selections are retained for review. Identical ALT IDs share a frame.',
                'frames': frames, 'selections': selections}
    js = '// Generated by tools/build_selected_items.py; edit CHOICES there.\n'
    js += 'const SelectedItemArt = ' + json.dumps(runtime, indent=2) + ';\n'
    return {OUT / 'items.png': png.getvalue(),
            OUT / 'manifest.json': (json.dumps(manifest, indent=2) + '\n').encode(),
            ROOT / 'src/selected_item_art.js': js.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify exports match current selected source crops')
    args = parser.parse_args()
    for path, data in outputs().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'Outdated export: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print('Selected items: 52 unique native crops, one 128x112 sheet; ' + ('verified' if args.check else 'exported'))


if __name__ == '__main__':
    main()
