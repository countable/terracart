#!/usr/bin/env python3
"""Export approved exact tileset crops and their runtime bounds (no resampling)."""
from pathlib import Path
import json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/StreetDecorations'
rows=json.loads((OUT/'sources.json').read_text())
widths={'young_fern':14,'pottery_stack_broken':14,'white_flower':10,'hanging_lantern':30,'wooden_lantern':24,'street_lantern':22,'tall_lantern':25,'fire_pedestal':24,'green_orb':24,'direction_sign':30,'mossy_tree':41,'conifer_tree':44,'dead_tree':52,'lavender_tree':54,'hedge_strip':48,'grass_clump':23,'stump':27,'spotted_mushroom':40,'dark_urn':24,'pottery_stack':25,'green_slick':26}
flat={'green_slick','plank_fragments','bone_fragments','dark_rubble','muted_stones'}
manifest={}
for key,row in rows.items():
 x,y,w,h=row['crop'];source=Image.open(ROOT/row['source']).convert('RGBA')
 image=source.crop((x,y,x+w,y+h));image.save(OUT/(key+'.png'))
 l,t,r,b=image.getbbox()
 manifest[key]={**row,'path':'assets/StreetDecorations/'+key+'.png','bounds':{'fw':w,'fh':h,'minX':l,'minY':t,'maxX':r,'maxY':b},'scale':round(widths.get(key,22)/(r-l),5),'ground':key in flat}
(ROOT/'src/street_decoration_art.js').write_text('// Generated by tools/build_street_decoration_art.py; exact approved source crops.\nconst STREET_DECORATION_ART = '+json.dumps(manifest,separators=(',',':'))+';\n')
print(f'Exported {len(manifest)} source crops and bounds')
