#!/usr/bin/env python3
"""Pack selected world sheets losslessly, retaining each logical key and frame.

Run the selection exporters first after changing their choices. Individual
exports remain reproducible source artifacts; runtime loads this atlas only.
Terrain remains its already-consolidated strip because its painter reads pixels
by tile coordinates. Trial trees/water remain opt-in and outside this atlas.
"""
import argparse
import io
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/Objects/SelectedWorld'
ATLAS_PATH = 'assets/Objects/SelectedWorld/world.png'
ATLAS_KEY = 'selected_world_atlas'
EXCLUDED = {'torch', 'selected_rubble'}  # Latest item choices now own these.


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated files without writing them')
    args = parser.parse_args()
    sources = []
    for directory in ['SelectedProps', 'SelectedFlora']:
        for path in sorted((ROOT / 'assets/Objects' / directory).glob('*.png')):
            if path.stem in EXCLUDED:
                continue
            image = Image.open(path).convert('RGBA')
            fw, fh = (24, 24) if path.stem == 'cave_mechanisms' else (16, 32) if path.stem == 'selected_grave_pillar' else (16, 16)
            assert image.width % fw == 0 and image.height % fh == 0
            sources.append((path, image, fw, fh))
    # Pack entire logical sheets so existing numeric frame order remains exact.
    # Two transparent pixels between sheets prevent neighbouring art bleeding.
    width = 256
    x = y = row_height = 0
    entries = {}
    placements = []
    for path, image, fw, fh in sorted(sources, key=lambda s: (-s[1].height, -s[1].width, s[0].stem)):
        assert image.width <= width
        if x + image.width > width:
            x = 0
            y += row_height + 2
            row_height = 0
        rects = {}
        for local_y in range(0, image.height, fh):
            for local_x in range(0, image.width, fw):
                rects[len(rects)] = dict(x=x+local_x, y=y+local_y, width=fw, height=fh)
        entries[path.stem] = dict(kind='atlas-alias', path=ATLAS_PATH, atlasKey=ATLAS_KEY,
                                  frameWidth=fw, frameHeight=fh,
                                  sheetRect=dict(x=x, y=y, width=image.width, height=image.height),
                                  frameRects=rects, sourcePath=str(path.relative_to(ROOT)))
        placements.append((image, x, y))
        x += image.width + 2
        row_height = max(row_height, image.height)
    atlas = Image.new('RGBA', (width, y + row_height))
    for image, x, y in placements:
        atlas.paste(image, (x, y))
    # Assert every exported frame is pixel-identical after packing.
    for path, image, fw, fh in sources:
        for frame, rect in entries[path.stem]['frameRects'].items():
            sx, sy = frame % (image.width // fw) * fw, frame // (image.width // fw) * fh
            assert atlas.crop((rect['x'], rect['y'], rect['x']+fw, rect['y']+fh)).tobytes() == image.crop((sx, sy, sx+fw, sy+fh)).tobytes()
    png = io.BytesIO()
    atlas.save(png, format='PNG', optimize=True)
    data = dict(key=ATLAS_KEY, path=ATLAS_PATH, width=atlas.width, height=atlas.height,
                entries=entries)
    outputs = {
        OUT / 'world.png': png.getvalue(),
        OUT / 'manifest.json': (json.dumps(data, indent=2) + '\n').encode(),
        ROOT / 'src/selected_world_atlas.js': (
            '// Generated by tools/build_selected_world_atlas.py; do not edit.\n'
            'const SelectedWorldAtlas = ' + json.dumps(data, separators=(',', ':')) + ';\n').encode(),
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise SystemExit(f'Out of date: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f'{len(entries)} logical sheets, {sum(len(e["frameRects"]) for e in entries.values())} frames → {ATLAS_PATH} ({atlas.width}×{atlas.height})')


if __name__ == '__main__':
    main()
