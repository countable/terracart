#!/usr/bin/env python3
"""Export 48px dialog atlases and their item-to-cell map from generated masters."""
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'assets/Icons/DialogItems'


def build():
    catalog = json.loads((DEST / 'catalog.json').read_text())
    # These generated cells changed the object's identity; use existing art.
    rejected = {(3, 44): 'Throwing spear became a wooden stick.',
                (3, 62): 'Barricade became scattered gold objects.'}
    entries, sheets = {}, []
    for number in range(1, 6):
        source = DEST / 'source' / f'generated-{number:02}.png'
        output = DEST / f'items-{number:02}.png'
        with Image.open(source) as master:
            image = master.convert('RGBA').resize((384, 384), Image.Resampling.NEAREST)
        image.save(output)
        digest = hashlib.sha256(output.read_bytes()).hexdigest()
        sheets.append({'source': str(source.relative_to(ROOT)),
                       'output': str(output.relative_to(ROOT)), 'sha256': digest,
                       'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest()})
        for row in catalog:
            if row['referenceSheet'] != number:
                continue
            frame = row['referenceCell']
            if (number, frame) in rejected or row.get('badge') or row.get('base') or row.get('paletteTransform'):
                continue
            x, y = (frame % 8) * 48, (frame // 8) * 48
            if not image.crop((x, y, x + 48, y + 48)).getchannel('A').getbbox():
                raise ValueError(f'Empty dialog art: {row["id"]}')
            entries[row['id']] = {'sheet': f'{output.relative_to(ROOT)}?v={digest[:8]}', 'frame': frame}
    runtime = {'cell': 48, 'columns': 8, 'size': 384, 'entries': entries}
    (ROOT / 'src/dialog_item_art.js').write_text(
        '// Generated by tools/build_dialog_item_art.py. Large portraits only.\n'
        + 'const DialogItemArt = ' + json.dumps(runtime, indent=2) + ';\n')
    (DEST / 'manifest.json').write_text(json.dumps({
        'cell': 48, 'columns': 8, 'rows': 8, 'sheets': sheets,
        'method': 'Image generation using 8x8 original-icon reference sheets; nearest-neighbor export to 384x384. Original transparency retained.',
        'excludedCells': [{'sheet': s, 'frame': f, 'reason': reason} for (s, f), reason in rejected.items()],
        'composites': 'Badged, base-derived and palette-transformed items retain existing composed art.',
        'runtimeEntries': len(entries),
    }, indent=2) + '\n')
    print(f'Exported five dialog atlases, {len(entries)} eligible item/gear portraits')


if __name__ == '__main__':
    build()
