#!/usr/bin/env python3
"""Export 96px dialog atlases and their item-to-cell map from generated masters."""
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'assets/Icons/DialogItems'
CELL = 96
COLUMNS = ROWS = 8


def export_master(master):
    """Resize each painted cell separately so filtering cannot bleed neighbours."""
    rgba = master.convert('RGBA')
    black = Image.new('RGBA', rgba.size, (0, 0, 0, 255))
    black.alpha_composite(rgba)
    source = black.convert('RGB')
    image = Image.new('RGB', (COLUMNS * CELL, ROWS * CELL))
    for frame in range(COLUMNS * ROWS):
        x, y = frame % COLUMNS, frame // COLUMNS
        bounds = (round(x * source.width / COLUMNS),
                  round(y * source.height / ROWS),
                  round((x + 1) * source.width / COLUMNS),
                  round((y + 1) * source.height / ROWS))
        tile = source.crop(bounds).resize((CELL, CELL), Image.Resampling.LANCZOS)
        image.paste(tile, (x * CELL, y * CELL))
    return image


def build():
    catalog = json.loads((DEST / 'catalog.json').read_text())
    entries, sheets = {}, []
    for number in range(1, 6):
        source = DEST / 'source' / f'generated-{number:02}.png'
        output = DEST / f'items-{number:02}.png'
        with Image.open(source) as master:
            image = export_master(master)
        image.save(output)
        digest = hashlib.sha256(output.read_bytes()).hexdigest()
        sheets.append({'source': str(source.relative_to(ROOT)),
                       'output': str(output.relative_to(ROOT)), 'sha256': digest,
                       'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest()})
        for row in catalog:
            if row['referenceSheet'] != number:
                continue
            frame = row['referenceCell']
            x, y = (frame % COLUMNS) * CELL, (frame // COLUMNS) * CELL
            row['outputCrop'] = [x, y, CELL, CELL]
            if not image.crop((x, y, x + CELL, y + CELL)).convert('L').point(
                    lambda value: 255 if value > 12 else 0).getbbox():
                raise ValueError(f'Empty dialog art: {row["id"]}')
            entries[row['id']] = {'sheet': f'{output.relative_to(ROOT)}?v={digest[:8]}', 'frame': frame}
    runtime = {'cell': CELL, 'columns': COLUMNS, 'size': COLUMNS * CELL, 'entries': entries}
    (DEST / 'catalog.json').write_text(json.dumps(catalog, indent=2) + '\n')
    (ROOT / 'src/dialog_item_art.js').write_text(
        '// Generated by tools/build_dialog_item_art.py. Large portraits only.\n'
        + 'const DialogItemArt = ' + json.dumps(runtime, indent=2) + ';\n')
    (DEST / 'manifest.json').write_text(json.dumps({
        'cell': CELL, 'columns': COLUMNS, 'rows': ROWS, 'sheets': sheets,
        'method': 'Sundries story-panel reference: muted painterly pixel art on black. Each generated 8x8 master cell is composited on black and independently exported with Lanczos filtering to 96x96; atlases are 768x768.',
        'styleReference': 'docs/art/story-style-references.json#sundries',
        'excludedCells': [],
        'composites': 'All catalog entries use generated base portraits; runtime preserves badges and variant colour treatments.',
        'runtimeEntries': len(entries),
    }, indent=2) + '\n')
    print(f'Exported five dialog atlases, {len(entries)} eligible item/gear portraits')


if __name__ == '__main__':
    build()
