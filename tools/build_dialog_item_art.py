#!/usr/bin/env python3
"""Export 96px dialog atlases and their item-to-cell map from generated masters."""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'assets/Icons/DialogItems'
SOURCE = ROOT / 'extra_assets/inactive/assets/Icons/DialogItems/source'
CELL = 96
COLUMNS = ROWS = 8
PADDING = 6


def ink_mask(image):
    """Ignore near-black generation noise when finding the painted objects."""
    red, green, blue = image.convert('RGB').split()
    return ImageChops.lighter(ImageChops.lighter(red, green), blue).point(
        lambda value: 255 if value > 12 else 0)


def gutters(mask, count, axis):
    """Find a clear separator near each nominal grid line, never through art."""
    extent = mask.height if axis == 'y' else mask.width
    boundaries = [0]
    for index in range(1, count):
        ideal = index * extent / count
        candidates = range(round((index - .4) * extent / count),
                           round((index + .4) * extent / count))
        for position in sorted(candidates, key=lambda value: abs(value - ideal)):
            strip = ((0, position, mask.width, position + 1) if axis == 'y'
                     else (position, 0, position + 1, mask.height))
            if mask.crop(strip).getbbox() is None:
                boundaries.append(position)
                break
        else:
            raise ValueError(f'No clear {axis} gutter for grid line {index}')
    return boundaries + [extent]


def export_master(master):
    """Recover uneven painted cells, then fit complete portraits to regular cells."""
    rgba = master.convert('RGBA')
    black = Image.new('RGBA', rgba.size, (0, 0, 0, 255))
    black.alpha_composite(rgba)
    source = black.convert('RGB')
    mask = ink_mask(source)
    row_edges = gutters(mask, ROWS, 'y')
    image = Image.new('RGB', (COLUMNS * CELL, ROWS * CELL))
    for y in range(ROWS):
        top, bottom = row_edges[y:y + 2]
        column_edges = gutters(mask.crop((0, top, source.width, bottom)), COLUMNS, 'x')
        for x in range(COLUMNS):
            left, right = column_edges[x:x + 2]
            tile = source.crop((left, top, right, bottom))
            painted = ink_mask(tile).getbbox()
            if painted is None:
                continue
            # Retain antialiased edges while discarding the irregular source margin.
            bounds = (max(0, painted[0] - 2), max(0, painted[1] - 2),
                      min(tile.width, painted[2] + 2), min(tile.height, painted[3] + 2))
            tile = tile.crop(bounds)
            tile.thumbnail((CELL - 2 * PADDING, CELL - 2 * PADDING), Image.Resampling.LANCZOS)
            image.paste(tile, (x * CELL + (CELL - tile.width) // 2,
                               y * CELL + (CELL - tile.height) // 2))
    return image


def build():
    catalog = json.loads((DEST / 'catalog.json').read_text())
    entries, sheets = {}, []
    for number in range(1, 6):
        source = SOURCE / f'generated-{number:02}.png'
        output = DEST / f'items-{number:02}.png'
        with Image.open(source) as master:
            image = export_master(master)
        image.save(output)
        digest = hashlib.sha256(output.read_bytes()).hexdigest()
        sheets.append({'source': str(source.relative_to(ROOT)),
                       'output': str(output.relative_to(ROOT)), 'sha256': digest,
                       'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest()})
        for row in catalog:
            if row['referenceSheet'] != number:
                continue
            frame = row['referenceCell']
            x, y = (frame % COLUMNS) * CELL, (frame // COLUMNS) * CELL
            row['outputCrop'] = [x, y, CELL, CELL]
            if not image.crop((x, y, x + CELL, y + CELL)).convert('L').point(
                    lambda value: 255 if value > 12 else 0).getbbox():
                raise ValueError(f'Empty dialog art: {row["id"]}')
            entries[row['id']] = {'sheet': f'{output.relative_to(ROOT)}?v={digest[:8]}', 'frame': frame}
    runtime = {'cell': CELL, 'columns': COLUMNS, 'size': COLUMNS * CELL, 'entries': entries}
    (DEST / 'catalog.json').write_text(json.dumps(catalog, indent=2) + '\n')
    (ROOT / 'src/dialog_item_art.js').write_text(
        '// Generated by tools/build_dialog_item_art.py. Large portraits only.\n'
        + 'const DialogItemArt = ' + json.dumps(runtime, indent=2) + ';\n')
    (DEST / 'manifest.json').write_text(json.dumps({
        'cell': CELL, 'columns': COLUMNS, 'rows': ROWS, 'sheets': sheets,
        'method': 'Sundries story-panel reference: muted painterly pixel art on black. Clear black gutters recover uneven rows and columns in each generated 8x8 master. Complete portraits are centered with at least 6px padding and Lanczos filtering in 96x96 cells; atlases are 768x768.',
        'styleReference': 'docs/art/story-style-references.json#sundries',
        'excludedCells': [],
        'composites': 'All catalog entries use generated base portraits; runtime preserves badges and variant colour treatments.',
        'runtimeEntries': len(entries),
    }, indent=2) + '\n')
    print(f'Exported five dialog atlases, {len(entries)} eligible item/gear portraits')


if __name__ == '__main__':
    build()
